-- Drop existing tables if any (for clean rebuild)
DROP TABLE IF EXISTS attendees CASCADE;

-- =====================================================
-- TABLE: attendees
-- Stores all registrant data with payment & check-in status
-- =====================================================
CREATE TABLE attendees (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  unique_id TEXT UNIQUE NOT NULL,              -- Auto-generated unique ID (e.g., "NATAL-001")
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,                         -- WhatsApp number
  school TEXT,                                 -- Required if status = 'siswa'
  status TEXT NOT NULL CHECK (status IN ('siswa', 'umum_alumni')),
  
  -- Payment fields
  payment_proof TEXT,                          -- URL/path to payment proof image
  payment_amount TEXT,                         -- Payment amount (as text for flexibility)
  payment_status TEXT DEFAULT 'pending' CHECK (payment_status IN ('pending', 'verified', 'rejected')),
  
  -- QR Code fields
  qr_code TEXT,                                -- QR code data/URL (generated by admin)
  qr_generated BOOLEAN DEFAULT FALSE,
  
  -- Check-in fields
  checked_in BOOLEAN DEFAULT FALSE,
  checked_in_at TIMESTAMPTZ,
  
  -- Timestamps
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- =====================================================
-- INDEXES for faster queries
-- =====================================================
CREATE INDEX idx_attendees_email ON attendees(email);
CREATE INDEX idx_attendees_unique_id ON attendees(unique_id);
CREATE INDEX idx_attendees_payment_status ON attendees(payment_status);
CREATE INDEX idx_attendees_qr_generated ON attendees(qr_generated);
CREATE INDEX idx_attendees_checked_in ON attendees(checked_in);

-- =====================================================
-- ROW LEVEL SECURITY (RLS)
-- =====================================================
ALTER TABLE attendees ENABLE ROW LEVEL SECURITY;

-- Policy: Allow anonymous insert (for registration)
CREATE POLICY "Allow anonymous insert" ON attendees
  FOR INSERT WITH CHECK (true);

-- Policy: Allow anonymous select (for checking registration)
CREATE POLICY "Allow anonymous select" ON attendees
  FOR SELECT USING (true);

-- Policy: Allow anonymous update (for admin updates)
CREATE POLICY "Allow anonymous update" ON attendees
  FOR UPDATE USING (true);

-- =====================================================
-- FUNCTION: Auto-update updated_at timestamp
-- =====================================================
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger for auto-updating updated_at
CREATE TRIGGER update_attendees_updated_at
  BEFORE UPDATE ON attendees
  FOR EACH ROW
  EXECUTE FUNCTION update_updated_at_column();

-- =====================================================
-- FUNCTION: Generate unique ID
-- Format: NATAL-XXXX (4 digit number)
-- =====================================================
CREATE OR REPLACE FUNCTION generate_unique_id()
RETURNS TEXT AS $$
DECLARE
  new_id TEXT;
  counter INTEGER;
BEGIN
  SELECT COUNT(*) + 1 INTO counter FROM attendees;
  new_id := 'NATAL-' || LPAD(counter::TEXT, 4, '0');
  RETURN new_id;
END;
$$ LANGUAGE plpgsql;

